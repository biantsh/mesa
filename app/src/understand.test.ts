import { describe, expect, it } from "vitest";
import type { Category } from "./api";
import { chooseDateEnd, chooseFileType, keepChosen, monthOf, understand, understandChosen, type Chosen } from "./understand";

const NOW = new Date(2026, 10, 2, 12);

type Row = [query: string, fileType: Category | null, from: string | null, to: string | null, text: string];

function check(rows: Row[]) {
  it.each(rows)("%s", (query, fileType, from, to, text) => {
    const understood = understand(query, NOW);
    expect({
      fileType: understood.fileType,
      from: understood.from?.label ?? null,
      to: understood.to?.label ?? null,
      text: understood.text,
    }).toEqual({ fileType, from, to, text });
  });
}

function checkDates(rows: [query: string, from: string | null, to: string | null][]) {
  it.each(rows)("%s", (query, from, to) => {
    const understood = understand(query, NOW);
    expect([understood.from?.label ?? null, understood.to?.label ?? null]).toEqual([from, to]);
  });
}

function checkTypes(rows: [query: string, fileType: Category | null][]) {
  it.each(rows)("%s", (query, fileType) => {
    expect(understand(query, NOW).fileType).toEqual(fileType);
  });
}

